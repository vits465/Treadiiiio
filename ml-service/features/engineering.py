import pandas as pd
import numpy as np
import pandas_ta_classic as ta

def compute_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Computes technical indicators from a DataFrame of price candles using pandas-ta.
    df must contain: 'open', 'high', 'low', 'close', 'volume'
    Returns a new DataFrame with feature columns added.
    """
    df = df.copy()
    
    if 'time' in df.columns:
        df['time'] = pd.to_datetime(df['time'])
        df = df.sort_values('time').reset_index(drop=True)
        
    for col in ['open', 'high', 'low', 'close', 'volume']:
        df[col] = pd.to_numeric(df[col])
        
    # --- 1. Moving Averages & Trend ---
    df.ta.sma(length=9, append=True)
    df.ta.sma(length=21, append=True)
    df.ta.ema(length=12, append=True)
    df.ta.ema(length=26, append=True)
    
    # Rename for consistency with existing model
    df.rename(columns={'SMA_9': 'sma_9', 'SMA_21': 'sma_21', 'EMA_12': 'ema_12', 'EMA_26': 'ema_26'}, inplace=True)

    # --- 2. MACD ---
    df.ta.macd(fast=12, slow=26, signal=9, append=True)
    df.rename(columns={'MACD_12_26_9': 'macd', 'MACDh_12_26_9': 'macd_hist', 'MACDs_12_26_9': 'macd_signal'}, inplace=True)
    
    # --- 3. RSI ---
    df.ta.rsi(length=14, append=True)
    df.rename(columns={'RSI_14': 'rsi_14'}, inplace=True)
    
    # --- 4. Bollinger Bands ---
    df.ta.bbands(length=20, std=2, append=True)
    df.rename(columns={
        'BBL_20_2.0': 'bb_lower', 
        'BBM_20_2.0': 'bb_middle', 
        'BBU_20_2.0': 'bb_upper',
        'BBB_20_2.0': 'bb_width'
    }, inplace=True)
    
    # --- 5. ATR (Average True Range) ---
    df.ta.atr(length=14, append=True)
    df.rename(columns={'ATRr_14': 'atr_14'}, inplace=True)
    
    # --- 6. Momentum / Rate of Change ---
    df.ta.roc(length=10, append=True)
    df.rename(columns={'ROC_10': 'roc_10'}, inplace=True)
    
    # --- 7. Additional Advanced ML & Regime Features ---
    df.ta.stoch(append=True) # Stochastic Oscillator
    df.ta.adx(length=14, append=True)   # ADX (Trend Strength)
    if 'ADX_14' in df.columns:
        df.rename(columns={'ADX_14': 'adx_14'}, inplace=True)
    elif 'adx' not in df.columns:
        df['adx_14'] = 20.0
    df.ta.obv(append=True)   # On-Balance Volume
    
    # Fill NaN values generated by ta indicators
    df.bfill(inplace=True)
    df.ffill(inplace=True)

    # --- 8. Stationary Price Ratios and ATR Percentile Rank ---
    atr_vals = df['atr_14'].clip(lower=1e-5)
    # Rolling 100-bar percentile rank of ATR (0.0 to 1.0)
    rolling_min = atr_vals.rolling(100, min_periods=10).min()
    rolling_max = atr_vals.rolling(100, min_periods=10).max()
    denom = (rolling_max - rolling_min).replace(0, 1e-5)
    df['atr_percentile'] = ((atr_vals - rolling_min) / denom).clip(0.0, 1.0).fillna(0.5)

    # Stationary ratios: distance from moving averages normalized by ATR
    df['price_to_sma21_atr'] = ((df['close'] - df['sma_21']) / atr_vals).clip(-10.0, 10.0).fillna(0.0)
    df['sma_diff_atr'] = ((df['sma_9'] - df['sma_21']) / atr_vals).clip(-10.0, 10.0).fillna(0.0)

    # --- 9. Strategy Indicator Encodings & Time Features ---
    close_vals = np.asarray(df['close']).squeeze()
    sma9_vals = np.asarray(df['sma_9']).squeeze()
    sma21_vals = np.asarray(df['sma_21']).squeeze()
    rsi14_vals = np.asarray(df['rsi_14']).squeeze()
    bb_lower_vals = np.asarray(df['bb_lower']).squeeze()
    bb_upper_vals = np.asarray(df['bb_upper']).squeeze()

    if bb_lower_vals.ndim > 1: bb_lower_vals = bb_lower_vals[:, 0]
    if bb_upper_vals.ndim > 1: bb_upper_vals = bb_upper_vals[:, 0]
    if sma9_vals.ndim > 1: sma9_vals = sma9_vals[:, 0]
    if sma21_vals.ndim > 1: sma21_vals = sma21_vals[:, 0]
    if rsi14_vals.ndim > 1: rsi14_vals = rsi14_vals[:, 0]
    if close_vals.ndim > 1: close_vals = close_vals[:, 0]

    df['feat_ma_crossover'] = np.where(sma9_vals > sma21_vals, 1.0, -1.0)
    df['feat_rsi_reversion'] = np.where(rsi14_vals < 30, 1.0, np.where(rsi14_vals > 70, -1.0, 0.0))
    df['feat_bollinger_reversion'] = np.where(close_vals < bb_lower_vals, 1.0, np.where(close_vals > bb_upper_vals, -1.0, 0.0))
    
    # Time & Session Features (UTC based)
    if 'time' in df.columns:
        hours = df['time'].dt.hour
        df['hour_of_day'] = hours.astype(float)
        df['day_of_week'] = df['time'].dt.dayofweek.astype(float)
        df['is_london'] = ((hours >= 7) & (hours < 16)).astype(float)
        df['is_ny'] = ((hours >= 13) & (hours < 21)).astype(float)
        df['is_asian'] = ((hours >= 0) & (hours < 9)).astype(float)
    else:
        df['hour_of_day'] = 12.0
        df['day_of_week'] = 2.0
        df['is_london'] = 1.0
        df['is_ny'] = 0.0
        df['is_asian'] = 0.0

    # Ensure no residual NaNs
    df.bfill(inplace=True)
    df.ffill(inplace=True)
    df.fillna(0.0, inplace=True)

    # Drop duplicate columns to prevent DataFrame indexing issues in XGBoost
    df = df.loc[:, ~df.columns.duplicated()]

    return df

def compute_triple_barrier_labels(
    df: pd.DataFrame,
    sl_mult: float = 1.5,
    tp_mult: float = 3.0,
    holding_period: int = 24
) -> pd.Series:
    """
    Computes Triple-Barrier Method labels matching actual engine SL/TP multipliers:
      - 2: BUY (price hits upper TP barrier before lower SL barrier within holding period)
      - 0: SELL (price hits lower TP barrier before upper SL barrier within holding period)
      - 1: HOLD (neither target barrier hit before holding period expiry or stop-loss touched)
    The last `holding_period` rows return NaN because the evaluation window is incomplete.
    """
    n = len(df)
    labels = np.full(n, np.nan, dtype=float)
    closes = df['close'].values
    highs = df['high'].values
    lows = df['low'].values
    atrs = df['atr_14'].values if 'atr_14' in df.columns else (highs - lows)

    for i in range(n - holding_period):
        entry_price = closes[i]
        atr = atrs[i] if atrs[i] > 0 else (entry_price * 0.001)
        
        # Long barriers
        long_tp = entry_price + atr * tp_mult
        long_sl = entry_price - atr * sl_mult
        
        # Short barriers
        short_tp = entry_price - atr * tp_mult
        short_sl = entry_price + atr * sl_mult

        max_look = min(i + 1 + holding_period, n)
        
        buy_success = False
        buy_stopped = False
        sell_success = False
        sell_stopped = False

        for j in range(i + 1, max_look):
            # Check Long path
            if not buy_stopped and not buy_success:
                if highs[j] >= long_tp and lows[j] > long_sl:
                    buy_success = True
                elif lows[j] <= long_sl:
                    buy_stopped = True

            # Check Short path
            if not sell_stopped and not sell_success:
                if lows[j] <= short_tp and highs[j] < short_sl:
                    sell_success = True
                elif highs[j] >= short_sl:
                    sell_stopped = True

        if buy_success and not sell_success:
            labels[i] = 2.0  # BUY
        elif sell_success and not buy_success:
            labels[i] = 0.0  # SELL
        else:
            labels[i] = 1.0  # HOLD

    return pd.Series(labels, index=df.index, name='target')

